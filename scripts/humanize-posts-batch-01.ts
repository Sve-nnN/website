// Merge the recovery-pass dictionary on top of the original hand-authored
// one. No key collisions expected (EXTRA_REWRITES keys are leaves the
// original dict never successfully matched), but a later spread wins if any
// do collide, since the recovery pass was authored against the true live
// leaf boundaries.
for (const [idStr, dict] of Object.entries(EXTRA_REWRITES)) {
  const id = Number(idStr)
  const existing = REWRITES[id] ?? { es: {}, en: {} }
  REWRITES[id] = {
    es: { ...existing.es, ...dict.es },
    en: { ...existing.en, ...dict.en },
  }
}

