function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function stripEmDash(text: string): string {
  // No em dashes exist in this batch's source (confirmed during authoring),
  // kept as a forward-safety net in case any slip in from a future re-run.
  return text.replace(/\s*—\s*/g, ', ').replace(/—/g, ',')
}

// JS regex `\b` is ASCII-only (`\w` = [A-Za-z0-9_]) — a voceo form ending in
// an accented vowel (Usá, Verificá, Renderizá...) has NO `\b` after the final
// "á", since an accented letter is treated as a non-word character just like
// the whitespace/punctuation that follows it (no word/non-word transition,
// so `\b` never matches there). Use explicit Latin-accented-aware
// lookbehind/lookahead boundaries instead of `\b`.
const WORD_CHAR_CLASS = 'A-Za-z0-9À-ÿ_'

function fixVoceo(text: string): string {
  let out = text
  for (const [from, to] of VOCEO_PAIRS) {
    const pattern = new RegExp(
      `(?<![${WORD_CHAR_CLASS}])${escapeRegExp(from)}(?![${WORD_CHAR_CLASS}])`,
      'g',
    )
    out = out.replace(pattern, to)
  }
  return out
}

function mechanicalFix(text: string): string {
  return fixVoceo(stripEmDash(text))
}

