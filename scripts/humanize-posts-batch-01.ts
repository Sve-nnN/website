function rewriteNode(node: LexicalNode, parentType: string | null, dict: Record<string, string>): LexicalNode {
  if (node === null || node === undefined) return node
  if (node.type === 'block' || node.type === 'table') return node

  if (node.type === 'text' && typeof node.text === 'string') {
    if (parentType === 'link') return node
    const isCode = typeof node.format === 'number' && (node.format & 16) === 16
    if (isCode) return node
    if (parentType !== 'heading' && parentType !== 'paragraph' && parentType !== 'listitem') return node

    const original = node.text
    const authored = dict[original]
    const newText = authored !== undefined ? authored : mechanicalFix(original)
    if (newText === original) return node
    return { ...node, text: newText }
  }

  if (Array.isArray(node.children)) {
    return { ...node, children: node.children.map((child) => rewriteNode(child, node.type, dict)) }
  }

  return node
}

