type Progress = Record<string, 'done'>

function loadProgress(): Progress {
  if (fs.existsSync(PROGRESS_PATH)) {
    return JSON.parse(fs.readFileSync(PROGRESS_PATH, 'utf8')) as Progress
  }
  return {}
}

function saveProgress(progress: Progress) {
  fs.mkdirSync(path.dirname(PROGRESS_PATH), { recursive: true })
  fs.writeFileSync(PROGRESS_PATH, JSON.stringify(progress, null, 2))
}

async function main() {
  const payload = await getPayload({ config })
  const progress = loadProgress()

  // Confirm each id exists live before processing anything.
  for (const id of IDS) {
    const doc = await payload.findByID({ collection: 'posts', id, depth: 0 }).catch(() => null)
    if (!doc) {
      console.error(`FATAL: posts id=${id} does not exist live. Aborting without processing any id.`)
      process.exit(1)
    }
  }

  let allOk = true

  for (const id of IDS) {
    if (progress[String(id)] === 'done') {
      console.log(`id=${id}: already done, skipping.`)
      continue
    }

    console.log(`id=${id}: processing...`)
    const before = await payload.findByID({ collection: 'posts', id, locale: 'all', depth: 0 })
    // NOTE: Payload's richText field value shape is always `{ root: LexicalNode }`,
    // even for a single locale — `content.es`/`content.en` are each `{ root }`
    // wrappers, NOT the root node itself. Every tree walk below operates on
    // `.root`, and every write re-wraps as `{ root: <rewritten> }`.
    const beforeContent = (before as unknown as { content: { es: { root: LexicalNode }; en: { root: LexicalNode } } })
      .content

    const dict = REWRITES[id] ?? { es: {}, en: {} }
    const missingLocales = new Set(KNOWN_MISSING_LOCALE_CONTENT[id] ?? [])
    const protectedBefore = {
      es: collectProtectedNodes(beforeContent.es?.root),
      en: collectProtectedNodes(beforeContent.en?.root),
    }

    for (const locale of ['es', 'en'] as const) {
      const originalRoot = beforeContent[locale]?.root
      if (!originalRoot || missingLocales.has(locale)) {
        console.log(`id=${id}: locale=${locale} has no existing content live — skipping (see KNOWN_MISSING_LOCALE_CONTENT).`)
        continue
      }
      const rewrittenRoot = rewriteNode(originalRoot, null, dict[locale])
      await payload.update({
        collection: 'posts',
        id,
        locale,
        data: { content: { root: rewrittenRoot } as unknown as Record<string, unknown> },
      })
    }

    // Read back to confirm the write persisted, and run the self-check.
    const after = await payload.findByID({ collection: 'posts', id, locale: 'all', depth: 0 })
    const afterContent = (after as unknown as { content: { es: { root: LexicalNode }; en: { root: LexicalNode } } })
      .content

    let idOk = true
    const issues: string[] = []

    // Protected node byte-identity check (only for locales actually written).
    for (const locale of ['es', 'en'] as const) {
      if (missingLocales.has(locale)) continue
      const protectedAfter = collectProtectedNodes(afterContent[locale]?.root)
      if (JSON.stringify(protectedAfter) !== JSON.stringify(protectedBefore[locale])) {
        idOk = false
        issues.push(`${locale}: block/table nodes changed`)
      }
    }

    // Voceo + em dash check (es only for voceo; both for em dash, per plan).
    const esText = extractText(afterContent.es?.root)
    const enText = missingLocales.has('en') ? '' : extractText(afterContent.en?.root)
    const voceoFound = findVoceoMarkers(esText)
    if (voceoFound.length > 0) {
      idOk = false
      issues.push(`es: voceo markers found: ${voceoFound.join(', ')}`)
    }
    const esDash = countEmDash(esText)
    const enDash = countEmDash(enText)
    if (esDash > 0 || enDash > 0) {
      idOk = false
      issues.push(`em dash found: es=${esDash} en=${enDash}`)
    }
    const esCliches = findClicheMarkers(esText)
    const enCliches = findClicheMarkers(enText)
    if (esCliches.length > 0 || enCliches.length > 0) {
      idOk = false
      issues.push(`AI-cliché markers found: es=${esCliches.join(', ')} en=${enCliches.join(', ')}`)
    }

    if (idOk) {
      progress[String(id)] = 'done'
      saveProgress(progress)
      console.log(`id=${id}: OK, marked done.`)
    } else {
      allOk = false
      console.error(`id=${id}: SELF-CHECK FAILED — ${issues.join(' | ')}`)
    }
  }

  if (!allOk) {
    console.error('One or more posts failed self-check. Re-run after investigating.')
    process.exit(1)
  }

  console.log(`\n${IDS.length}/${IDS.length} posts in this batch confirmed done.`)
  process.exit(0)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
