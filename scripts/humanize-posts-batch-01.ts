function extractText(value: unknown): string {
  if (value === null || value === undefined) return ''
  if (typeof value === 'string') return value
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (Array.isArray(value)) return value.map(extractText).join('')
  if (typeof value === 'object') {
    const obj = value as Record<string, unknown>
    let out = ''
    if (typeof obj.text === 'string') out += obj.text
    if (Array.isArray(obj.children)) out += extractText(obj.children)
    if (!('text' in obj) && !('children' in obj)) {
      out += Object.values(obj).map(extractText).join('')
    }
    return out
  }
  return ''
}

// Plan's literal self-check marker list, plus every voceo form this batch's
// mechanical fixer knows about (VOCEO_PAIRS' "from" side, lowercased +
// deduped) — a superset, so the self-check actually verifies the fixer did
// its job instead of only checking the plan's example list.
const VOCEO_MARKERS = Array.from(
  new Set([
    'vos',
    'tenés',
    'podés',
    'querés',
    'sabés',
    'usás',
    'necesitás',
    'trabajás',
    'sospechás',
    'preferís',
    'mirá',
    ...VOCEO_PAIRS.map(([from]) => from.toLowerCase()),
  ]),
)

function findVoceoMarkers(text: string): string[] {
  const found: string[] = []
  for (const marker of VOCEO_MARKERS) {
    const re = new RegExp(`(?<![${WORD_CHAR_CLASS}])${escapeRegExp(marker)}(?![${WORD_CHAR_CLASS}])`, 'i')
    if (re.test(text)) found.push(marker)
  }
  return found
}

function countEmDash(text: string): number {
  return (text.match(/—/g) || []).length
}

// AI-cliché markers (added in the recovery pass — the plan's original
// self-check only covered voceo + em dash; a live spot-check on post id=9
// found "es esencial para garantizar" surviving the first run, so the
// self-check now also gates on these). Checked case-insensitively against
// both locales' extracted text.
const CLICHE_MARKERS = [
  'es esencial', 'es fundamental', 'cabe destacar', 'crucial', 'leverage', 'seamless', 'robust',
  'es importante mencionar', 'es importante destacar', 'no cabe duda', 'sin duda alguna',
]

function findClicheMarkers(text: string): string[] {
  const found: string[] = []
  const lower = text.toLowerCase()
  for (const marker of CLICHE_MARKERS) {
    if (lower.includes(marker.toLowerCase())) found.push(marker)
  }
  return found
}

// Collects every `block`/`table` node (stringified, not descended into) in
// document order, for pre/post byte-identity comparison.
function collectProtectedNodes(node: unknown, out: string[] = []): string[] {
  if (node === null || node === undefined) return out
  if (Array.isArray(node)) {
    for (const item of node) collectProtectedNodes(item, out)
    return out
  }
  if (typeof node === 'object') {
    const obj = node as LexicalNode
    if (obj.type === 'block' || obj.type === 'table') {
      out.push(JSON.stringify(obj))
      return out
    }
    if (Array.isArray(obj.children)) collectProtectedNodes(obj.children, out)
  }
  return out
}

